def blit_text(
    surf: pygame.Surface,
    text: str,
    x: int,
    y: int,
    color: tuple[int, int, int],
    scale: int = 1,
    shadow: tuple[int, int, int] | None = (0, 0, 0),
) -> pygame.Rect:
    px = x
    py = y
    max_x = x
    for ch in text.upper():
        if ch == "\n":
            py += 8 * scale
            px = x
            continue
        glyph = _GLYPHS.get(ch, _GLYPHS["?"])
        if shadow:
            _draw_glyph(surf, glyph, px + scale, py + scale, shadow, scale)
        _draw_glyph(surf, glyph, px, py, color, scale)
        px += 6 * scale
        max_x = max(max_x, px)
    return pygame.Rect(x, y, max_x - x, py - y + 7 * scale)


def text_width(text: str, scale: int = 1) -> int:
    lines = text.upper().split("\n")
    return max(len(line) * 6 * scale for line in lines) if lines else 0


def blit_text_center(
    surf: pygame.Surface,
    text: str,
    cx: int,
    y: int,
    color: tuple[int, int, int],
    scale: int = 1,
    shadow: tuple[int, int, int] | None = (0, 0, 0),
) -> pygame.Rect:
    w = text_width(text, scale)
    return blit_text(surf, text, cx - w // 2, y, color, scale, shadow)


def _draw_glyph(
    surf: pygame.Surface,
    glyph: tuple[str, ...],
    x: int,
    y: int,
    color: tuple[int, int, int],
    scale: int,
) -> None:
    for gy, row in enumerate(glyph):
        for gx, bit in enumerate(row):
            if bit == "1":
                surf.fill(
                    color,
                    (x + gx * scale, y + gy * scale, scale, scale),
                )


def dither_rect(
    surf: pygame.Surface,
    rect: pygame.Rect,
    a: tuple[int, int, int],
    b: tuple[int, int, int],
) -> None:
    for yy in range(rect.top, rect.bottom):
        for xx in range(rect.left, rect.right):
            surf.set_at((xx, yy), a if (xx + yy) % 2 == 0 else b)


def scanlines(surf: pygame.Surface, alpha: int = 40) -> None:
    overlay = pygame.Surface(surf.get_size(), pygame.SRCALPHA)
    h = surf.get_height()
    w = surf.get_width()
    for y in range(0, h, 2):
        overlay.fill((0, 0, 0, alpha), (0, y, w, 1))
    surf.blit(overlay, (0, 0))
